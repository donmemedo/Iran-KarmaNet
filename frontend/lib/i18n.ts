export type Locale = 'fa' | 'en'
export type Key = keyof typeof dict

export function translate(locale: Locale, key: Key, vars?: Record<string, string | number>) {
  let s: string = dict[key][locale === 'fa' ? 0 : 1]
  for (const k in vars) s = s.replace(`{${k}}`, String(vars[k]))
  return s
}

export const num = (n: number, l: Locale, digits = 1) =>
  new Intl.NumberFormat(l === 'fa' ? 'fa-IR' : 'en-US', { maximumFractionDigits: digits }).format(n)

/** Persian/Arabic digits → ASCII, so users can type in either keyboard. */
export const toAscii = (s: string) =>
  s.replace(/[۰-۹]/g, (d) => String('۰۱۲۳۴۵۶۷۸۹'.indexOf(d))).replace(/[٠-٩]/g, (d) => String('٠١٢٣٤٥٦٧٨٩'.indexOf(d)))
